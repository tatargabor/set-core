"""Generated, machine-local project role rules (fleet-era-consolidation, capability
`project-role-rule`).

Every registered project gets `.claude/rules/project-role.md`: what the project is for, what
it owns, what it depends on, what depends on it, and — for an archived entry — that it is
not to be developed. Claude Code loads rules at session start, so an agent opened in the
project knows its place without a hook.

Where the content comes from, and why it never leaves the machine
-----------------------------------------------------------------
The roles live in a file the operator maintains OUTSIDE every repository:
``<set-core config dir>/project-roles.yaml`` (``SET_CONFIG_DIR`` / XDG, the same directory as
the registry). A full project map names private projects and clients, so it can be neither
committed nor shipped. set-core ships only an empty example
(``templates/project-roles.example.yaml``).

The generated file is listed in the repository's ``info/exclude`` when it is written, so no
commit can carry it, and it opens with a generated-by marker: a regeneration overwrites only
a file carrying that marker, never a hand-written one.

Visibility
----------
A PUBLIC repository's rule names only PUBLIC siblings; a private relation is counted
("1 private project"). Visibility is decided the way ``set-leakscan`` decides it (its own
``remote_visibility``, with its per-URL cache). Each unknown is resolved in the direction
that names less: a sibling of unknown visibility is not named, and a project whose own
visibility is unknown is treated as public.
"""

from __future__ import annotations

import argparse
import importlib.machinery
import importlib.util
import json
import logging
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional

logger = logging.getLogger(__name__)

RULE_REL = ".claude/rules/project-role.md"
MARKER = "<!-- generated by `set-project roles` — do not edit; regenerated from the machine-local role file -->"
ROLE_FILE_NAME = "project-roles.yaml"

Visibility = Callable[[str], str]  # path -> "public" | "private" | "unknown"


def role_file_path(env: Optional[dict] = None) -> Path:
    from set_kb.lifecycle import config_dir  # one resolver for the config dir (B-175)

    return Path(config_dir(env)) / ROLE_FILE_NAME


def registry_file(env: Optional[dict] = None) -> Path:
    from set_kb.lifecycle import registry_path

    return Path(registry_path(env))


def load_roles(path: Path) -> Optional[dict]:
    """{name: entry} from the role file, or None when there is no role file."""
    if not path.is_file():
        return None
    import yaml

    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    projects = data.get("projects") if isinstance(data, dict) else None
    if not isinstance(projects, dict):
        logger.warning("role file has no 'projects' mapping: %s", path)
        return {}
    return {str(k): (v if isinstance(v, dict) else {}) for k, v in projects.items()}


ALLOWED_KEYS = {"role": "one line, text", "owns": "list of text", "depends_on": "list of registry names",
                "replaced_by": "one registry name"}


def validate(path: Path, registry: dict) -> list:
    """Problems in the role file, as sentences; empty when it is valid. Writes nothing."""
    import yaml

    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as e:
        return [f"unreadable: {e}"]
    if not isinstance(data, dict):
        return ["the top level must be a mapping with `version: 1` and `projects:`"]
    problems = []
    if data.get("version") != 1:
        problems.append(f"version must be 1, found {data.get('version')!r}")
    projects = data.get("projects")
    if not isinstance(projects, dict):
        return problems + ["`projects:` must be a mapping of registry name → entry"]
    for name, entry in projects.items():
        where = f"projects.{name}"
        if name not in registry:
            problems.append(f"{where}: not a registry name (`set-project list`)")
        if not isinstance(entry, dict):
            problems.append(f"{where}: must be a mapping")
            continue
        for k in entry:
            if k not in ALLOWED_KEYS:
                problems.append(f"{where}.{k}: unknown key (allowed: {', '.join(ALLOWED_KEYS)})")
        if "role" in entry and not isinstance(entry["role"], str):
            problems.append(f"{where}.role: must be text")
        for k in ("owns", "depends_on"):
            v = entry.get(k)
            if v is not None and not (isinstance(v, list) and all(isinstance(x, str) for x in v)):
                problems.append(f"{where}.{k}: must be a list of text")
        for dep in _as_list(entry.get("depends_on")):
            if dep == name:
                problems.append(f"{where}.depends_on: names the project itself")
            elif dep not in registry:
                problems.append(f"{where}.depends_on: {dep} is not a registry name")
        rb = entry.get("replaced_by")
        if rb is not None and (not isinstance(rb, str) or rb not in registry):
            problems.append(f"{where}.replaced_by: must be one registry name, found {rb!r}")
    return problems


def _leakscan_visibility() -> Visibility:
    """`set-leakscan`'s own remote_visibility — one definition of "public" on the machine."""
    script = Path(__file__).resolve().parents[2] / "bin" / "set-leakscan"
    loader = importlib.machinery.SourceFileLoader("_set_leakscan_for_roles", str(script))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    mod = importlib.util.module_from_spec(spec)
    loader.exec_module(mod)
    return lambda path: mod.remote_visibility(path) if os.path.isdir(path) else "unknown"


@dataclass
class Outcome:
    written: list = field(default_factory=list)
    unchanged: list = field(default_factory=list)
    skipped: list = field(default_factory=list)  # (name, reason)


def _as_list(v) -> list:
    if v is None:
        return []
    return [str(x) for x in v] if isinstance(v, (list, tuple)) else [str(v)]


def _relations(names: list, registry: dict, self_public: bool, vis: Visibility) -> str:
    """Render a relation list: everything for a private project; for a public one, public
    siblings by name and the rest as a count."""
    if not names:
        return "none"
    shown, hidden = [], 0
    for n in names:
        if not self_public:
            shown.append(n)
            continue
        path = os.path.expanduser(str((registry.get(n) or {}).get("path") or ""))
        if path and vis(path) == "public":
            shown.append(n)
        else:
            hidden += 1
    parts = [", ".join(f"`{n}`" for n in shown)] if shown else []
    if hidden:
        parts.append(f"{hidden} private project{'' if hidden == 1 else 's'}")
    return " + ".join(parts)


def render(name: str, entry: dict, role: Optional[dict], roles: dict, registry: dict, vis: Visibility) -> str:
    path = os.path.expanduser(str(entry.get("path") or ""))
    own = vis(path)
    self_public = own != "private"
    archived = entry.get("archived") is True
    lines = [MARKER, f"# Project role — {name}", ""]
    if archived:
        repl = _as_list((role or {}).get("replaced_by"))
        tail = f" It was replaced by {_relations(repl, registry, self_public, vis)}." if repl else ""
        lines += [f"> **ARCHIVED — do not develop this project.** Do not start new work here; a read or a",
                  f"> one-off fix the owner asks for is fine.{tail}", ""]
    vis_word = {"public": "public", "private": "private"}.get(own, "unknown (treated as public)")
    lines.append(f"Visibility: {vis_word}.")
    if role is None:
        lines += ["", "The role of this project is not described in the operator's role file."]
        return "\n".join(lines) + "\n"
    depended_by = sorted(n for n, r in roles.items() if name in _as_list(r.get("depends_on")))
    lines += [
        "",
        f"**Role:** {str(role.get('role') or 'not described').strip()}",
        "",
        f"**Owns:** {', '.join(_as_list(role.get('owns'))) or 'not described'}",
        "",
        f"**Depends on:** {_relations(_as_list(role.get('depends_on')), registry, self_public, vis)}",
        "",
        f"**Depended on by:** {_relations(depended_by, registry, self_public, vis)}",
    ]
    if self_public:
        lines += ["", "This repository is public: name only public projects in anything committed here."]
    return "\n".join(lines) + "\n"


def _git(path: str, *args) -> tuple:
    try:
        p = subprocess.run(["git", "-C", path, *args], capture_output=True, text=True, timeout=30)
        return p.returncode, p.stdout.strip()
    except (OSError, subprocess.SubprocessError) as e:
        return 1, str(e)


def ensure_excluded(root: str) -> bool:
    """Add the rule's path to the repository's info/exclude. True when it is excluded."""
    rc, rel = _git(root, "rev-parse", "--git-path", "info/exclude")
    if rc != 0 or not rel:
        return False
    excl = Path(rel) if os.path.isabs(rel) else Path(root) / rel
    line = "/" + RULE_REL
    existing = excl.read_text(encoding="utf-8").splitlines() if excl.is_file() else []
    if line not in existing:
        excl.parent.mkdir(parents=True, exist_ok=True)
        with excl.open("a", encoding="utf-8") as f:
            if existing and existing[-1] != "":
                f.write("\n")
            f.write("# set-core: machine-local project role rule, never committed\n" + line + "\n")
        logger.info("info/exclude: added %s in %s", line, root)
    return True


def generate(registry: dict, roles: Optional[dict], only: Optional[list] = None, dry_run: bool = False,
             vis: Optional[Visibility] = None) -> Outcome:
    out = Outcome()
    if roles is None:
        return out
    vis = vis or _leakscan_visibility()
    for name in sorted(registry):
        if only and name not in only:
            continue
        entry = registry[name] or {}
        path = os.path.expanduser(str(entry.get("path") or ""))
        if entry.get("deploy") is False:
            out.skipped.append((name, "data repository — set-core writes nothing into it"))
            continue
        if not path or not os.path.isdir(path) or _git(path, "rev-parse", "--show-toplevel")[0] != 0:
            out.skipped.append((name, "path missing or not a git repository"))
            continue
        target = Path(path) / RULE_REL
        content = render(name, entry, roles.get(name), roles, registry, vis)
        if target.exists():
            current = target.read_text(encoding="utf-8", errors="replace")
            if not current.startswith(MARKER):
                out.skipped.append((name, f"{RULE_REL} exists without the generated-by marker — left as is"))
                continue
            if current == content:
                out.unchanged.append(name)
                continue
        if _git(path, "ls-files", "--error-unmatch", RULE_REL)[0] == 0:
            out.skipped.append((name, f"{RULE_REL} is tracked by git — a machine-local rule cannot live there"))
            continue
        if not dry_run:
            if not ensure_excluded(path):
                out.skipped.append((name, "could not add the rule to info/exclude — not written"))
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            logger.info("project role rule written: %s", target)
        out.written.append(name)
    return out


def rule_state(path: str, env: Optional[dict] = None) -> tuple:
    """For the machine doctor: ("skip"|"warn"|"ok", detail)."""
    rf = role_file_path(env)
    if not rf.is_file():
        return "skip", f"no role file ({rf})"
    target = Path(os.path.expanduser(path)) / RULE_REL
    if not target.is_file():
        return "warn", f"{RULE_REL} is missing"
    if target.stat().st_mtime < rf.stat().st_mtime:
        return "warn", f"{RULE_REL} is older than the role file"
    return "ok", f"{RULE_REL} is current"


def main(argv: Optional[list] = None) -> int:
    ap = argparse.ArgumentParser(prog="set-project roles",
                                 description="Write the machine-local project role rule into every registered project.")
    ap.add_argument("names", nargs="*", metavar="NAME", help="only these registry entries")
    ap.add_argument("--dry-run", action="store_true", help="report only; writes nothing")
    ap.add_argument("--check", action="store_true", help="validate the role file against the registry; writes nothing")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(name)s: %(message)s")

    rf = role_file_path()
    roles = load_roles(rf)
    if roles is None:
        print(f"no role file — nothing written (looked for {rf}; "
              "start from templates/project-roles.example.yaml in set-core)")
        return 0
    try:
        registry = json.loads(registry_file().read_text(encoding="utf-8")).get("projects") or {}
    except (OSError, ValueError) as e:
        print(f"registry unreadable: {registry_file()}: {e}", file=sys.stderr)
        return 1
    if args.check:
        problems = validate(rf, registry)
        for line in problems:
            print(f"  {line}")
        print(f"role file {rf}: " + (f"{len(problems)} problem(s)" if problems else "valid"))
        return 1 if problems else 0
    unknown = [n for n in args.names if n not in registry]
    for n in unknown:
        print(f"not registered: {n}", file=sys.stderr)
    out = generate(registry, roles, only=args.names or None, dry_run=args.dry_run)
    verb = "would write" if args.dry_run else "written"
    print(f"project role rules: {len(out.written)} {verb}, {len(out.unchanged)} unchanged, {len(out.skipped)} skipped")
    for n in out.written:
        print(f"  {verb}: {n}")
    for n, why in out.skipped:
        print(f"  skipped: {n} — {why}")
    return 2 if unknown else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
